import unittest
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity


def get_similarity(text1, text2):
    """
    Основна обчислювальна функція програми.
    Використовує статистичну міру TF-IDF для перетворення тексту в вектори
    та косинусну схожість для порівняння цих векторів.
    """

    # --- БЛОК ВАЛІДАЦІЇ ---
    # Перевірка на наявність змістовного тексту.
    # Метод .strip() видаляє пробіли та символи переносу рядка.
    if not text1.strip() or not text2.strip():
        # Повертаємо 0, щоб уникнути помилок при векторизації порожніх даних
        return 0

    # --- ЕТАП ОБРОБКИ ---
    # Ініціалізація об'єкта TfidfVectorizer для побудови словника та матриці ваг
    vectorizer = TfidfVectorizer()

    # Побудова числового представлення (векторизація) вхідних документів
    tfidf = vectorizer.fit_transform([text1, text2])

    # Розрахунок косинусної метрики між першим та другим вектором.
    # Результат — число з плаваючою крапкою від 0.0 до 1.0.
    return cosine_similarity(tfidf[0:1], tfidf[1:2])[0][0]


class TestPlagiarismLogic(unittest.TestCase):
    """
    Набір Unit-тестів для перевірки надійності алгоритму
    згідно з принципами автоматизованого тестування ПЗ.
    """

    def test_identical(self):
        """Тест №1: Перевірка ідентичних текстів (Схожість має бути максимальною)"""
        text = "Програмування на мові Python — це захоплюючий процес."
        res = get_similarity(text, text)
        self.assertTrue(res > 0.9, f"Очікувався високий відсоток, отримано: {res}")

    def test_different(self):
        """Тест №2: Перевірка абсолютно різних за змістом текстів"""
        text_a = "Сьогодні сонячна погода"
        text_b = "Об'єктно-орієнтоване проектування систем"
        res = get_similarity(text_a, text_b)
        self.assertTrue(res < 0.3, f"Очікувався низький відсоток, отримано: {res}")

    def test_empty(self):
        """Тест №3: Перевірка обробки порожніх вхідних даних (Краш-тест)"""
        # Сценарій, коли один із файлів не містить тексту
        res = get_similarity("", "Деякий текст для порівняння")
        self.assertEqual(res, 0, "Програма повинна повертати 0 при порожньому вводі")


# Точка запуску тестів у разі автономного запуску модуля
if __name__ == "__main__":
    # Запуск вбудованого механізму тестування Python
    unittest.main()